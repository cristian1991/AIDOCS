def launch_prefix(home: Path | str | None = None, *, nt: bool | None = None) -> list[str]:
    """The argv prefix that runs the CURRENT generation's python via the stable
    launcher. Windows cannot spawn a ``.cmd`` without a shell, so it is wrapped
    in ``cmd /c`` exactly as Claude Code documents for script launchers."""
    is_nt = (os.name == "nt") if nt is None else nt
    b = bin_dir(home)
    if is_nt:
        return ["cmd", "/c", str(b / f"{PYTHON_LAUNCHER}.cmd")]
    return [str(b / PYTHON_LAUNCHER)]


def home_of_generation_interpreter(python_path: str) -> Path | None:
    """``<home>`` when ``python_path`` lives in
    ``<home>/.aidocs/runtime/generations/<id>/...``, else None."""
    parts = Path(str(python_path or "")).parts
    lowered = [p.lower() for p in parts]
    for i in range(len(parts) - 3):
        if lowered[i : i + 3] == [".aidocs", "runtime", rg.GENERATIONS_DIRNAME]:
            return Path(*parts[:i]) if i else None
    return None


def _is_link_or_reparse(path: Path) -> bool:
    try:
        st = os.lstat(path)
    except OSError:
        return True
    if path.is_symlink():
        return True
    return bool(getattr(st, "st_file_attributes", 0) & 0x400)  # FILE_ATTRIBUTE_REPARSE_POINT


def launchers_current(home: Path | str | None = None) -> bool:
    """Is the python launcher this platform's host entry would name current?

    EXACT-FILE EQUIVALENCE: a regular file (not a symlink or junction), at the
    generated path, byte-identical to the rendering. One byte different and it
    is not ours.
    """
    b = bin_dir(home)
    name = f"{PYTHON_LAUNCHER}.cmd" if os.name == "nt" else PYTHON_LAUNCHER
    if _is_link_or_reparse(b) or _is_link_or_reparse(b / name):
        return False
    body = _read(b / name)
    want = render_cmd(PYTHON_LAUNCHER) if name.endswith(".cmd") else render_posix(PYTHON_LAUNCHER)
    return body == want


def stable_mcp_command(python_path: str) -> tuple[str, list[str]] | None:
    """``(command, prefix_args)`` naming the generation-following launcher for a
    host MCP entry whose selected interpreter is a GENERATION interpreter, or
    None when the entry should name ``python_path`` itself (an operator pin, an
    ambient escape, a legacy install, or launchers that are not yet current —
    the entry must never name a launcher that would refuse)."""
    if str(os.environ.get("AIDOCS_PYTHON") or "").strip():
        return None
    home = home_of_generation_interpreter(python_path)
    if home is None or not launchers_current(home):
        return None
    prefix = launch_prefix(home)
    return prefix[0], prefix[1:]


def effective_interpreter(command: str | None, args: list | None, home: Path | str | None = None) -> str | None:
    """What a host MCP entry ACTUALLY EXECUTES, for the trust chain.

    An entry naming our current launcher runs the current generation's python —
    that IS the interpreter it governs with. Anything else is taken at its word.
    A launcher entry whose generation cannot resolve answers the launcher path,
    so the trust chain reports an honest mismatch instead of a pass.
    """
    if not command:
        return command
    argv = [str(command), *[str(a) for a in (args or [])]]
    prefix = launch_prefix(home)

    def _norm(s: str) -> str:
        s = s.replace("\\", "/")
        return s.lower() if os.name == "nt" else s

    head = [_norm(a) for a in argv[: len(prefix)]]
    want = [_norm(a) for a in prefix]
    if os.name == "nt" and head and head[0] in ("cmd.exe",):
        head[0] = "cmd"
    if head != want or not launchers_current(home):
        return command
    try:
        return str(rg.current_generation_python(home))
    except rg.CurrentGenerationError:
        return prefix[-1]


# ── the STATIC stdio shim (#1202, design decision B) ────────────────────────
#
# The shim is the STABLE part of the MCP path: a stdlib-only relay that builds
# identity headers and forwards JSON-RPC to the daemon over HTTP. Only the
# daemon behind it is volatile, and the daemon is restarted under the new
# generation by the watchdog. So host config names a FIXED FILE run by the same
# stable interpreter the hook shim uses (#925j), never a generation path and
# never a launcher that has to resolve one.
#
# stdio_shim.py and window_key.py are stdlib-only by construction; they are
# placed VERBATIM (byte-identical to the packaged, tested sources) beside the
# hook shim. The content is refreshed on every flip; the PATH never changes.

STDIO_SHIM_BASENAME = "aidocs_mcp_stdio_shim.py"
#: (packaged source, deployed sibling name). Written BEFORE the shim, so a new
#: shim never lands without the module it imports.
STDIO_SHIM_COMPANIONS: tuple[tuple[str, str], ...] = (("window_key.py", "aidocs_window_key.py"),)
#: Interpreter flags for the static shim, and link 1 requires EXACTLY these:
#:   -E  ignore PYTHON* env;   -s  no user site;
#:   -S  NO `site` AT ALL (r0b2 r2): the stable interpreter is the legacy venv's,
#:       and its site.py would otherwise execute .pth lines and sitecustomize
#:       -- unverified code -- before the shim's first line. The shim is
#:       stdlib-only, so it needs no site-packages.
#: Not -I: that also drops the script directory from sys.path, which is how
#: the sibling aidocs_window_key module is found; -S keeps sys.path[0].
STDIO_SHIM_FLAGS: tuple[str, ...] = ("-E", "-s", "-S")
REASON_STDIO_SHIM_NOT_PLACED = "static_stdio_shim_missing_or_stale"


def stdio_shim_path(home: Path | str | None = None) -> Path:
    """The FIXED path of the static stdio shim — beside the hook shim."""
    from .claude_hooks_install import shim_path

    return shim_path(Path(home) if home else None).with_name(STDIO_SHIM_BASENAME)


def _stdio_shim_files() -> dict[str, str]:
    here = Path(__file__).resolve().parent
    out = {dest: (here / src).read_text(encoding="utf-8") for src, dest in STDIO_SHIM_COMPANIONS}
    out[STDIO_SHIM_BASENAME] = (here / "stdio_shim.py").read_text(encoding="utf-8")
    return out


def stdio_shim_current(home: Path | str | None = None) -> bool:
    """EXACT-FILE EQUIVALENCE: every deployed file is a regular file (no link),
    byte-identical to the packaged source, in a directory that is not a link."""
    d = stdio_shim_path(home).parent
    if _is_link_or_reparse(d):
        return False
    for name, text in _stdio_shim_files().items():
        p = d / name
        if _is_link_or_reparse(p) or _read(p) != text:
            return False
    return True


def ensure_stdio_shim(home: Path | str | None = None) -> dict:
    """Place (or refresh) the static shim and its companion. Idempotent.

    Same P3 discipline as ``ensure_launchers``: ``~/.aidocs`` and the runtime
    directory must be real directories inside the real home (no symlink,
    junction or reparse point); writes go through a temp file in that verified
    directory and re-check its identity before replacing.
    """
    base = Path(home) if home else Path.home()
    d = stdio_shim_path(base).parent
    res: dict = {"ok": True, "path": str(d / STDIO_SHIM_BASENAME), "changed": [], "errors": []}
    try:
        real_home = base.resolve(strict=True)
        for level in (base / ".aidocs", d):
            if not os.path.lexists(level):
                level.mkdir()
            _verify_plain_dir(level, real_home)
        ident = _dir_identity(d)
    except OSError as exc:
        res.update(ok=False, refused=True)
        res["errors"].append(str(exc))
        return res
    for name, text in _stdio_shim_files().items():
        p = d / name
        if _read(p) == text and not _is_link_or_reparse(p):
            continue
        try:
            _atomic_write(p, text, executable=False, dir_identity=ident)
            res["changed"].append(str(p))
        except OSError as exc:
            res["ok"] = False
            res["errors"].append(f"{p}: {exc}")
            if isinstance(exc, _UnsafeBinDir):
                res["refused"] = True
            break
    return res


def _is_generation_path(p: str) -> bool:
    return "/generations/" in str(p or "").replace("\\", "/")


def static_shim_argv(home: Path | str | None = None) -> list[str]:
    """``[stable python, -E, -s, -S, <fixed shim path>]`` for a host MCP entry, or RAISE.

    The interpreter is the hook shim's stable launcher (operator pin first,
    then the base interpreter outside ``generations/``). If the only
    interpreter is a generation one, the generation-following launcher stands
    in for it; if neither exists, or the shim is not placed, this refuses —
    an entry naming a generation path is exactly the defect (#1202).
    """
    if not stdio_shim_current(home):
        raise rg.CurrentGenerationError(
            REASON_STDIO_SHIM_NOT_PLACED,
            f"the static stdio shim at {stdio_shim_path(home)} is missing or stale",
        )
    from .claude_hooks_install import stable_launcher_python

    pin = str(os.environ.get("AIDOCS_PYTHON") or "").strip()
    py = pin or stable_launcher_python(Path(home) if home else None)
    tail = [*STDIO_SHIM_FLAGS, str(stdio_shim_path(home))]
    if pin or (py and not _is_generation_path(py) and _is_owned_stable(py, home)):
        return [py, *tail]
    if launchers_current(home):
        return [*launch_prefix(home), *tail]
    raise rg.CurrentGenerationError(
        REASON_LAUNCHER_NOT_CURRENT,
        "no stable AIDOCS interpreter outside runtime/generations and the "
        f"{PYTHON_LAUNCHER} launcher is missing or stale",
    )


def _is_owned_stable(py: str, home: Path | str | None) -> bool:
    """Is ``py`` under the AIDOCS runtime root (and not ambient)?"""
    from .claude_hooks_install import shim_path

    root = str(shim_path(Path(home) if home else None).parent).replace("\\", "/").rstrip("/").lower()
    p = str(py).replace("\\", "/").lower()
    return p.startswith(root + "/")


def is_static_shim_entry(command: str | None, args: list | None, home: Path | str | None = None) -> bool:
    """Does this host MCP entry run EXACTLY the static shim, exactly as
    ``static_shim_argv`` would write it today, over a byte-identical shim?"""
    if not command:
        return False
    try:
        want = static_shim_argv(home)
    except rg.CurrentGenerationError:
        return False

    def _norm(s: str) -> str:
        s = str(s).replace("\\", "/")
        return s.lower() if os.name == "nt" else s

    got = [_norm(command), *[_norm(a) for a in (args or [])]]
    if os.name == "nt" and got and got[0] == "cmd.exe":
        got[0] = "cmd"
    return got == [_norm(a) for a in want]


def reconcile_entry_points(home: Path | str | None = None) -> dict:
    """Create or refresh EVERY stable entry point: the ~/.aidocs/bin launchers
    and the static stdio shim. Run under the NEW generation's code after a
    flip (daemon boot, ``--reconcile-hook-shim``), so the first update that
    carries #1202 converges with no manual step."""
    return {"launchers": ensure_launchers(home, create=True), "stdio_shim": ensure_stdio_shim(home)}
