"""Generation-resolving entry-point launchers in ``~/.aidocs/bin`` (#1202).

THE DEFECT. ``~/.aidocs/bin/{aidocs,aidocs-mcp}`` (POSIX sh) and their ``.cmd``
twins were hand-placed on 2026-08-19 (#727) and named the LEGACY single-tree
venv directly. Runtime generations (#1030) moved the real runtime to
``runtime/generations/<id>/`` and nothing ever rewrote the launchers, so for a
month every ``aidocs`` CLI call and the OpenCode MCP server ran a package dated
2026-09-28 — enforcing stale gate/judge law — while the daemon and the Claude
Code hooks ran the current generation and every health surface was green.

THE CURE. A launcher never names a runtime. It reads ``runtime/current.json``
AT EXEC TIME, validates the generation id against the strict shape
(``runtime_generations.CURRENT_GENERATION_ID_PATTERN``), requires the
generation's seal, and execs that generation's entry point. Anything else is a
loud non-zero exit naming the cause and the remedy. There is no fallback to the
legacy tree in any branch: a launcher that cannot find the current runtime
must say so, because a launcher that quietly runs an older one is the bug.

The POSIX version needs no python to read the pointer (sed + grep), and the
``.cmd`` version uses ``findstr`` with the strict shape spelled out
character-class by character-class, so a crafted ``current.json`` (``../``,
quotes, spaces, shell metacharacters) is refused before it can name a path.

ONE WRITER. ``ensure_launchers`` renders all of them from the templates below,
idempotently. It runs from ``aidocs setup``, ``aidocs runtime --fix``, the
``--reconcile-hook-shim`` step that follows every pointer flip, and the
provisioner right after a generation is activated — so a stale launcher is
rewritten by the next routine maintenance instead of surviving forever.

``aidocs-python`` is the stable interpreter launcher for HOST CONFIG
(.mcp.json, OpenCode's MCP entry): those used to bake in a generation-specific
interpreter path, which goes stale at the next update and is removable by GC.
"""

from __future__ import annotations

import os
import re
import tempfile
from pathlib import Path

from . import runtime_generations as rg

#: launcher basename -> the generation venv entry point it runs.
LAUNCHERS: dict[str, str] = {
    "aidocs": "aidocs",
    "aidocs-mcp": "aidocs-mcp",
    "aidocs-python": "python",
}

#: The stable interpreter launcher host MCP entries name.
PYTHON_LAUNCHER = "aidocs-python"

#: Version-bearing marker. A launcher carrying an older marker is stale and is
#: rewritten; one carrying none is a hand-placed or pre-#1202 launcher.
LAUNCHER_MARKER = "AIDOCS generation-resolving launcher (#1202) v1"
_MARKER_PREFIX = "AIDOCS generation-resolving launcher (#1202)"

#: Exit status of every launcher refusal (EX_CONFIG).
LAUNCHER_REFUSAL_EXIT = 78

_LAUNCHER_REMEDY = (
    "run `aidocs runtime --fix` from a working AIDOCS interpreter -- it activates "
    "a sealed generation and rewrites these launchers. This launcher never falls "
    "back to the legacy venv."
)

#: What a pre-#1202 launcher names, for drift reporting only.
_LEGACY_TARGET_RE = re.compile(r"[\\/]\.aidocs[\\/]runtime[\\/]venv[\\/]", re.IGNORECASE)
_PINNED_GENERATION_RE = re.compile(r"[\\/]generations[\\/]([A-Za-z0-9._-]+)[\\/]", re.IGNORECASE)


def bin_dir(home: Path | str | None = None) -> Path:
    return (Path(home) if home else Path.home()) / ".aidocs" / "bin"


def render_posix(name: str) -> str:
    entry = LAUNCHERS[name]
    pattern = rg.CURRENT_GENERATION_ID_PATTERN
    return f"""#!/bin/sh
# {LAUNCHER_MARKER}
# GENERATED by aidocs_mcp.runtime_launchers -- `aidocs runtime --fix` rewrites it.
# Runs the CURRENT runtime generation's `{entry}`, resolved at EXEC time:
#   runtime/current.json -> runtime/generations/<id>/venv/(Scripts/{entry}.exe | bin/{entry})
# It FAILS LOUDLY (exit {LAUNCHER_REFUSAL_EXIT}) when that cannot be resolved and never
# falls back to the legacy single-tree venv. No python is needed to read the pointer.
_aidocs_rt="${{AIDOCS_RUNTIME_ROOT:-${{HOME:-}}/.aidocs/runtime}}"
_aidocs_die() {{
  printf 'aidocs launcher ({name}): %s\\n' "$1" >&2
  printf 'aidocs launcher ({name}): remedy: %s\\n' '{_LAUNCHER_REMEDY}' >&2
  exit {LAUNCHER_REFUSAL_EXIT}
}}
_aidocs_ptr="$_aidocs_rt/current.json"
[ -f "$_aidocs_ptr" ] || _aidocs_die "no activation pointer at $_aidocs_ptr"
_aidocs_gid=$(sed -n 's/^[[:space:]]*{{[[:space:]]*"generation_id"[[:space:]]*:[[:space:]]*"\\([^"]*\\)"[[:space:]]*}}[[:space:]]*$/\\1/p' "$_aidocs_ptr")
case "$_aidocs_gid" in
  ''|*[!0-9A-Za-z-]*) _aidocs_die "activation pointer $_aidocs_ptr is malformed or names an invalid generation id" ;;
esac
printf '%s\\n' "$_aidocs_gid" | grep -Eqx '{pattern}' || _aidocs_die "activation pointer $_aidocs_ptr names an invalid generation id"
_aidocs_gen="$_aidocs_rt/generations/$_aidocs_gid"
[ -d "$_aidocs_gen" ] || _aidocs_die "generation $_aidocs_gid is not on disk ($_aidocs_gen)"
[ -f "$_aidocs_gen/{rg.COMPLETE_MARKER}" ] || _aidocs_die "generation $_aidocs_gid was never sealed"
if [ -f "$_aidocs_gen/venv/Scripts/{entry}.exe" ]; then
  exec "$_aidocs_gen/venv/Scripts/{entry}.exe" "$@"
fi
if [ -f "$_aidocs_gen/venv/bin/{entry}" ]; then
  exec "$_aidocs_gen/venv/bin/{entry}" "$@"
fi
_aidocs_die "generation $_aidocs_gid has no {entry} entry point under venv/Scripts or venv/bin"
"""


def render_cmd(name: str) -> str:
    """The ``.cmd`` twin. PURE BATCH, no findstr, no PowerShell.

    findstr was the first cut and is unusable here: its ``[a-f]`` ranges are
    collation-ordered (they match uppercase), it has no ``{n}``, and the
    enumerated spelling of the strict shape exceeds its search-string limit.
    So the pointer line is read once with ``for /f``, and the id is validated
    position by position with CASE-SENSITIVE ``if`` comparisons against the
    strict shape — every character, before the id is joined onto any path.
    Delayed expansion is enabled only for that check (its ``!var!`` reads are
    never re-parsed, so quotes, ``&`` or ``|`` in a crafted pointer stay data)
    and is off again before ``%*`` reaches the target.
    """
    entry = LAUNCHERS[name]
    digit_list = " ".join("0123456789")
    hex_list = " ".join("0123456789abcdef")
    lines = [
        "@echo off",
        f"rem {LAUNCHER_MARKER}",
        "rem GENERATED by aidocs_mcp.runtime_launchers -- `aidocs runtime --fix` rewrites it.",
        f"rem Runs the CURRENT runtime generation's {entry}.exe, resolved at EXEC time from",
        "rem runtime\\current.json. It FAILS LOUDLY when that cannot be resolved and never",
        "rem falls back to the legacy single-tree venv.",
        "setlocal EnableExtensions DisableDelayedExpansion",
        'set "AIDOCS_LX_RT=%USERPROFILE%\\.aidocs\\runtime"',
        'if defined AIDOCS_RUNTIME_ROOT set "AIDOCS_LX_RT=%AIDOCS_RUNTIME_ROOT%"',
        'set "AIDOCS_LX_PTR=%AIDOCS_LX_RT%\\current.json"',
        'if not exist "%AIDOCS_LX_PTR%" goto :aidocs_no_pointer',
        'set "AIDOCS_LX_RAW="',
        'set "AIDOCS_LX_GID="',
        'set "AIDOCS_LX_N=0"',
        # ONE read of the pointer; exactly one non-empty line or refuse.
        'for /f "usebackq delims=" %%L in ("%AIDOCS_LX_PTR%") do (',
        '  set "AIDOCS_LX_RAW=%%L"',
        "  set /a AIDOCS_LX_N+=1",
        ")",
        'if not "%AIDOCS_LX_N%"=="1" goto :aidocs_bad_pointer',
        "setlocal EnableDelayedExpansion",
        # The literal framing json.dump writes: {"generation_id": "<id>"}
        'set "AIDOCS_LX_WANT_HEAD={"generation_id": ""',
        'set "AIDOCS_LX_WANT_TAIL="}"',
        'if not "!AIDOCS_LX_RAW:~0,19!"=="!AIDOCS_LX_WANT_HEAD!" goto :aidocs_bad_pointer',
        'if not "!AIDOCS_LX_RAW:~-2!"=="!AIDOCS_LX_WANT_TAIL!" goto :aidocs_bad_pointer',
        'set "AIDOCS_LX_ID=!AIDOCS_LX_RAW:~19,-2!"',
        # gen-YYYYMMDDTHHMMSSZ-<hex>: 21 fixed characters, then 1..43 hex.
        'if not "!AIDOCS_LX_ID:~0,4!"=="gen-" goto :aidocs_bad_pointer',
        'if not "!AIDOCS_LX_ID:~12,1!"=="T" goto :aidocs_bad_pointer',
        'if not "!AIDOCS_LX_ID:~19,1!"=="Z" goto :aidocs_bad_pointer',
        'if not "!AIDOCS_LX_ID:~20,1!"=="-" goto :aidocs_bad_pointer',
        'if "!AIDOCS_LX_ID:~21,1!"=="" goto :aidocs_bad_pointer',
        'if not "!AIDOCS_LX_ID:~64!"=="" goto :aidocs_bad_pointer',
        'set "AIDOCS_LX_BAD="',
        "for /l %%I in (4,1,63) do (",
        '  set "AIDOCS_LX_C=!AIDOCS_LX_ID:~%%I,1!"',
        "  if defined AIDOCS_LX_C (",
        '    set "AIDOCS_LX_OK="',
        "    if %%I GEQ 21 (",
        f'      for %%H in ({hex_list}) do if "!AIDOCS_LX_C!"=="%%H" set "AIDOCS_LX_OK=1"',
        "    ) else if %%I EQU 12 (",
        '      set "AIDOCS_LX_OK=1"',
        "    ) else if %%I GEQ 19 (",
        '      set "AIDOCS_LX_OK=1"',
        "    ) else (",
        f'      for %%D in ({digit_list}) do if "!AIDOCS_LX_C!"=="%%D" set "AIDOCS_LX_OK=1"',
        "    )",
        '    if not defined AIDOCS_LX_OK set "AIDOCS_LX_BAD=1"',
        "  )",
        ")",
        "if defined AIDOCS_LX_BAD goto :aidocs_bad_pointer",
        # Validated: only [0-9a-zTZ-] remain, so a percent expansion is safe.
        'for %%G in ("!AIDOCS_LX_ID!") do endlocal & set "AIDOCS_LX_GID=%%~G"',
        'set "AIDOCS_LX_GEN=%AIDOCS_LX_RT%\\generations\\%AIDOCS_LX_GID%"',
        f'if not exist "%AIDOCS_LX_GEN%\\{rg.COMPLETE_MARKER}" goto :aidocs_unsealed',
        f'set "AIDOCS_LX_EXE=%AIDOCS_LX_GEN%\\venv\\Scripts\\{entry}.exe"',
        'if not exist "%AIDOCS_LX_EXE%" goto :aidocs_no_entry',
        'endlocal & "%AIDOCS_LX_EXE%" %*',
        "exit /b %ERRORLEVEL%",
        ":aidocs_no_pointer",
        f'>&2 echo aidocs launcher ({name}): no activation pointer at "%AIDOCS_LX_PTR%"',
        "goto :aidocs_remedy",
        ":aidocs_bad_pointer",
        f'>&2 echo aidocs launcher ({name}): activation pointer "%AIDOCS_LX_PTR%" is malformed or names an invalid generation id',
        "goto :aidocs_remedy",
        ":aidocs_unsealed",
        f">&2 echo aidocs launcher ({name}): generation %AIDOCS_LX_GID% is not on disk or was never sealed",
        "goto :aidocs_remedy",
        ":aidocs_no_entry",
        f">&2 echo aidocs launcher ({name}): generation %AIDOCS_LX_GID% has no {entry}.exe under venv\\Scripts",
        "goto :aidocs_remedy",
        ":aidocs_remedy",
        f">&2 echo aidocs launcher ({name}): remedy: {_LAUNCHER_REMEDY}",
        f"exit /b {LAUNCHER_REFUSAL_EXIT}",
    ]
    return "\r\n".join(lines) + "\r\n"


def expected_launchers(home: Path | str | None = None) -> dict[Path, str]:
    """Every launcher path -> the exact text it must hold."""
    b = bin_dir(home)
    out: dict[Path, str] = {}
    for name in LAUNCHERS:
        out[b / name] = render_posix(name)
        out[b / f"{name}.cmd"] = render_cmd(name)
    return out


def _read(path: Path) -> str | None:
    try:
        return path.read_bytes().decode("utf-8", "replace")
    except OSError:
        return None


class _UnsafeBinDir(OSError):
    """``~/.aidocs/bin`` (or ``~/.aidocs``) is not a plain directory we own."""


def _dir_identity(path: Path) -> tuple[int, int]:
    st = os.lstat(path)
    return (st.st_dev, st.st_ino)


def _verify_plain_dir(path: Path, real_home: Path) -> tuple[int, int]:
    """``path`` is a REAL directory — not a symlink, junction or other reparse
    point — inside the real home and (POSIX) owned by this user. Returns its
    lstat identity so a later re-check can prove nothing was swapped in."""
    if _is_link_or_reparse(path):
        raise _UnsafeBinDir(f"{path} is a symlink, junction or reparse point; refusing to write through it")
    st = os.lstat(path)
    import stat as _stat

    if not _stat.S_ISDIR(st.st_mode):
        raise _UnsafeBinDir(f"{path} is not a directory")
    if hasattr(os, "getuid") and st.st_uid != os.getuid():
        raise _UnsafeBinDir(f"{path} is not owned by this user")
    try:
        resolved = path.resolve(strict=True)
    except OSError as exc:
        raise _UnsafeBinDir(f"{path} cannot be resolved: {exc}") from exc
    if resolved != real_home and real_home not in resolved.parents:
        raise _UnsafeBinDir(f"{path} resolves outside the home ({resolved})")
    return (st.st_dev, st.st_ino)


def _safe_bin_dir(home: Path | str | None, *, create: bool) -> Path | None:
    """The verified ``<home>/.aidocs/bin``, created level by level if asked;
    None when it is absent and ``create`` is False. Raises _UnsafeBinDir."""
    base = Path(home) if home else Path.home()
    try:
        real_home = base.resolve(strict=True)
    except OSError as exc:
        raise _UnsafeBinDir(f"home {base} cannot be resolved: {exc}") from exc
    aidocs = base / ".aidocs"
    b = aidocs / "bin"
    for level in (aidocs, b):
        if not os.path.lexists(level):
            if not create:
                return None
            level.mkdir()
        _verify_plain_dir(level, real_home)
    return b


def _atomic_write(path: Path, text: str, *, executable: bool, dir_identity: tuple[int, int]) -> None:
    """Temp file in the SAME verified directory, then replace — after proving
    the directory is still the one that was verified (nothing swapped a link
    in between)."""
    fd, tmp = tempfile.mkstemp(prefix=".aidocs-launcher-", dir=str(path.parent))
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(text.encode("utf-8"))
            fh.flush()
            os.fsync(fh.fileno())
        if executable:
            os.chmod(tmp, 0o755)
        if _is_link_or_reparse(path.parent) or _dir_identity(path.parent) != dir_identity:
            raise _UnsafeBinDir(f"{path.parent} changed while writing; refusing to replace {path.name}")
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def ensure_launchers(home: Path | str | None = None, *, create: bool = True) -> dict:
    """Write every launcher whose bytes differ from its rendering. Idempotent.

    ``create=False`` (the post-activation call) only REWRITES: on a box with no
    ``~/.aidocs/bin`` it does nothing, so a provisioning run on a build host or
    in a test never invents a bin directory. Never deletes anything, and never
    touches a file in ``bin`` that is not one of ours (``aidocs-dashboard.cmd``).

    REFUSES (ok=False, nothing written) when ``~/.aidocs`` or ``~/.aidocs/bin``
    is a symlink, junction or other reparse point, is not owned by this user
    or resolves outside the real home: a rewrite must never escape the
    directory it was asked to repair (r0b2 P3).
    """
    b = bin_dir(home)
    res: dict = {"ok": True, "bin": str(b), "changed": [], "unchanged": [], "errors": []}
    try:
        safe = _safe_bin_dir(home, create=create)
        if safe is None:
            res["skipped"] = "no_bin_dir"
            return res
        ident = _dir_identity(safe)
    except OSError as exc:
        res["ok"] = False
        res["refused"] = True
        res["errors"].append(str(exc))
        return res
    for path, text in expected_launchers(home).items():
        if _read(path) == text and not _is_link_or_reparse(path):
            res["unchanged"].append(str(path))
            continue
        try:
            _atomic_write(path, text, executable=not path.name.endswith(".cmd"), dir_identity=ident)
            res["changed"].append(str(path))
        except OSError as exc:
            res["ok"] = False
            res["errors"].append(f"{path}: {exc}")
            if isinstance(exc, _UnsafeBinDir):
                res["refused"] = True
                break
    return res


#: Why a host entry cannot name the stable launcher right now.
REASON_LAUNCHER_NOT_CURRENT = "generation_launcher_missing_or_stale"


def owned_interpreter_argv(home: Path | str | None = None, *, allow_generation_path: bool) -> list[str]:
    """argv prefix that runs the AIDOCS-OWNED interpreter, or RAISE (#1202, r0b2 P1).

    The operator pin (``AIDOCS_PYTHON``) wins. Otherwise the CURRENT sealed
    generation: through the generation-following launcher when it is current,
    or — only where the caller says the config is EPHEMERAL
    (``allow_generation_path``) — the generation's python directly. There is
    no ambient, PATH or bare-``python`` answer: no owned runtime means refuse.
    """
    pin = str(os.environ.get("AIDOCS_PYTHON") or "").strip()
    if pin:
        return [pin]
    py = rg.current_generation_python(home)
    if launchers_current(home):
        return launch_prefix(home)
    if allow_generation_path:
        return [str(py)]
    raise rg.CurrentGenerationError(
        REASON_LAUNCHER_NOT_CURRENT,
        f"the {PYTHON_LAUNCHER} launcher in {bin_dir(home)} is missing or stale, and persisted "
        "host config must never name a runtime generation",
    )


def _current_generation_or_reason(home: Path | str | None) -> tuple[str, str]:
    try:
        gid, _ = rg.current_generation_dir(home)
        return gid, ""
    except rg.CurrentGenerationError as exc:
        return "", exc.reason


def _legacy_venv_state(home: Path | str | None, current_gid: str) -> dict:
    """Is the legacy single-tree venv present, and OLDER than the current
    generation? Reported, never removed: its interpreter may still host the
    stdlib hook shim (#925j), and deleting user files is the operator's call."""
    base = Path(home) if home else Path.home()
    legacy = rg.runtime_root(base) / rg.LEGACY_VENV_DIRNAME
    state: dict = {"path": str(legacy), "present": legacy.is_dir(), "stale": None}
    if not state["present"]:
        state["stale"] = False
        return state
    pkgs = [
        *legacy.glob("Lib/site-packages/aidocs_mcp/__init__.py"),
        *legacy.glob("lib/python*/site-packages/aidocs_mcp/__init__.py"),
    ]
    if not pkgs or not current_gid:
        return state
    gdir = rg.generation_dir(base, current_gid)
    seal = gdir / rg.COMPLETE_MARKER if gdir else None
    try:
        legacy_mtime = max(p.stat().st_mtime for p in pkgs)
        current_mtime = seal.stat().st_mtime if seal else None
    except OSError:
        return state
    if current_mtime is None:
        return state
    state["stale"] = legacy_mtime < current_mtime
    return state


def launcher_status(home: Path | str | None = None) -> dict:
    """LAUNCHER DRIFT: does every launcher present run the CURRENT generation?

    ``drift`` is True when any launcher is not the current generation-resolving
    rendering — a pre-#1202 launcher naming the legacy venv, one pinned to a
    specific generation, or an older generated version. Absent launchers are
    reported, not counted as drift (a box may simply not use them).

    ``legacy_venv.stale`` is reported SEPARATELY: an old legacy tree is not, by
    itself, a launcher pointing at it, and conflating the two would leave this
    axis red forever on a box that keeps the tree for its hook interpreter.
    """
    gid, why = _current_generation_or_reason(home)
    entries: list[dict] = []
    drift = False
    for path, text in expected_launchers(home).items():
        body = _read(path)
        row: dict = {"path": str(path)}
        if body is None:
            row["state"] = "absent"
        elif body == text:
            row["state"] = "current"
        elif _MARKER_PREFIX in body:
            row["state"] = "stale_generated"
        elif _LEGACY_TARGET_RE.search(body):
            row["state"] = "legacy_venv_target"
        else:
            m = _PINNED_GENERATION_RE.search(body)
            if m:
                row["state"] = "pinned_generation" if m.group(1) != gid else "pinned_current_generation"
                row["pinned"] = m.group(1)
            else:
                row["state"] = "unrecognised"
        if row["state"] not in ("absent", "current"):
            drift = True
        entries.append(row)
    legacy = _legacy_venv_state(home, gid)
    remedy = ""
    if drift:
        remedy = (
            "run `aidocs runtime --fix` (rewrites ~/.aidocs/bin with launchers that "
            "follow runtime/current.json)"
        )
    if legacy.get("stale"):
        remedy = (remedy + "; " if remedy else "") + (
            f"the legacy venv at {legacy['path']} predates the current generation: "
            "nothing should import aidocs_mcp from it. Do NOT delete it while a hook "
            "entry in ~/.claude/settings.json still names its interpreter"
        )
    return {
        "ok": not drift and bool(gid),
        "drift": drift,
        "current_generation": gid,
        "current_generation_reason": why,
        "launchers": entries,
        "legacy_venv": legacy,
        "remedy": remedy,
    }


